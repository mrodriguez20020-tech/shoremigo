export function translate(lang: Lang, key: Key, vars?: Record<string, string>) {
  let s = DICTS[lang]?.[key] ?? en[key];
  for (const [k, v] of Object.entries(vars ?? {})) s = s.replace(`{${k}}`, v);
  return s;
}

